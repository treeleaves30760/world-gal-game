    def _draw_divider(self, surface: pygame.Surface) -> None:
        left = self._panel_rect.x + self._sp(24)
        right = self._panel_rect.right - self._sp(24)
        height = max(1, self._sp(6))
        rect = pygame.Rect(
            left,
            self._header_divider_y - height // 2,
            max(1, right - left + 1),
            height,
        )
        chrome = self.ctx.ui_chrome
        painted = (
            chrome is not None
            and chrome.paint(
                surface,
                rect,
                ChromeRequest(
                    part="divider",
                    screen="settings",
                    variant="header",
                    size=rect.size,
                    density=self._density,
                ),
            )
        )
        if not painted:
            pygame.draw.line(
                surface,
                self.ctx.theme.border_soft,
                (left, self._header_divider_y),
                (right, self._header_divider_y),
            )

    @staticmethod
    def _wrap_text(
        text: str,
        font: pygame.font.Font,
        max_width: int,
        *,
        max_lines: int,
    ) -> list[str]:
        remaining = " ".join(str(text).split())
        if not remaining:
            return []
        lines: list[str] = []
        while remaining and len(lines) < max_lines:
            end = 0
            while (
                end < len(remaining)
                and font.size(remaining[:end + 1])[0] <= max_width
            ):
                end += 1
            if end == 0:
                end = 1
            if end < len(remaining):
                break_at = remaining.rfind(" ", 0, end + 1)
                if break_at > 0:
                    end = break_at
            line = remaining[:end].rstrip()
            lines.append(line)
            remaining = remaining[end:].lstrip()
        if remaining and lines:
            suffix = "…"
            line = lines[-1]
            while line and font.size(line + suffix)[0] > max_width:
                line = line[:-1]
            lines[-1] = line.rstrip() + suffix
        return lines

    def _draw_status(self, surface: pygame.Surface) -> None:
        theme = self.ctx.theme
        chrome = self.ctx.ui_chrome
        painted = (
            chrome is not None
            and chrome.paint(
                surface,
                self._status_rect,
                ChromeRequest(
                    part="card",
                    screen="settings",
                    variant=f"controls-status:{self._status_kind}",
                    size=self._status_rect.size,
                    density=self._density,
                    selected=self._status_kind in {
                        "capture",
                        "success",
                        "warning",
                        "error",
                    },
                ),
            )
        )
        if not painted:
            bg = pygame.Surface(self._status_rect.size, pygame.SRCALPHA)
            pygame.draw.rect(
                bg,
                (*theme.bg_panel[:3], 230),
                bg.get_rect(),
                border_radius=theme.radius_m,
            )
            pygame.draw.rect(
                bg,
                theme.border_soft,
                bg.get_rect(),
                width=1,
                border_radius=theme.radius_m,
            )
            surface.blit(bg, self._status_rect.topleft)

        prefix = {
            "capture": "等待輸入",
            "success": "設定完成",
            "warning": "需要確認",
            "error": "無法套用",
        }.get(self._status_kind, "操作說明")
        color = {
            "success": theme.good,
            "warning": theme.accent_warm,
            "error": theme.warn,
            "capture": theme.accent,
        }.get(self._status_kind, theme.text_mute)
        font = self.ctx.fonts.get(self._status_font_size, bold=True)
        pad_x = self._sp(12)
        max_width = max(1, self._status_rect.width - pad_x * 2)
        lines = self._wrap_text(
            f"{prefix}：{self._status}",
            font,
            max_width,
            max_lines=2,
        )
        total_h = len(lines) * self._status_line_h
        y = self._status_rect.centery - total_h // 2
        for line in lines:
            rendered = font.render(line, True, color)
            surface.blit(rendered, (self._status_rect.x + pad_x, y))
            y += self._status_line_h

    def _footer_text(self) -> str:
        if self._capture_action is not None:
            return "按下新按鍵　Esc 取消；此時其他輸入不會生效"
        profile = self._profile()
        confirm = profile.primary_display(InputAction.CONFIRM_ADVANCE)
        back = profile.primary_display(InputAction.BACK)
        if self._reset_pending:
            return f"{confirm} 再次確認　{back} 取消恢復預設"
        nav_up = profile.primary_display(InputAction.NAV_UP)
        nav_down = profile.primary_display(InputAction.NAV_DOWN)
        return (
            f"{nav_up} / {nav_down} 移動　{confirm} 變更　"
            f"滑鼠滾輪捲動　{back} 返回"
        )

    def _draw_footer(self, surface: pygame.Surface) -> None:
        theme = self.ctx.theme
        chrome = self.ctx.ui_chrome
        painted = (
            chrome is not None
            and chrome.paint(
                surface,
                self._footer_rect,
                ChromeRequest(
                    part="footer",
                    screen="settings",
                    variant="hint",
                    size=self._footer_rect.size,
                    density=self._density,
                ),
            )
        )
        if not painted:
            pygame.draw.line(
                surface,
                theme.border_soft,
                self._footer_rect.topleft,
                self._footer_rect.topright,
            )
        font = self.ctx.fonts.get(self._footer_font_size, bold=True)
        text = self._footer_text()
        max_width = self._footer_rect.width - self._sp(20)
        if font.size(text)[0] > max_width:
            suffix = "…"
            while text and font.size(text.rstrip() + suffix)[0] > max_width:
                text = text[:-1]
            text = text.rstrip() + suffix
        rendered = font.render(text, True, theme.text_mute)
        surface.blit(
            rendered,
            (
                self._footer_rect.x + self._sp(10),
                self._footer_rect.centery - rendered.get_height() // 2,
            ),
        )

    def draw(self, surface: pygame.Surface) -> None:
        theme = self.ctx.theme
        chrome = self.ctx.ui_chrome
        backdrop = surface.get_rect()
        painted = (
            chrome is not None
            and chrome.paint(
                surface,
                backdrop,
                ChromeRequest(
                    part="backdrop",
                    screen="settings",
                    variant="overlay",
                    size=backdrop.size,
                    density=self._density,
                ),
            )
        )
        if not painted:
            veil = pygame.Surface(surface.get_size(), pygame.SRCALPHA)
            veil.fill((0, 0, 0, 236))
            surface.blit(veil, (0, 0))

        self._panel.draw(surface)
        surface.blit(self._title_surface, self._title_rect.topleft)
        self.close_btn.draw(surface)
        self._draw_divider(surface)

        self._reposition()
        self._sync_focus_state()
        body = self._body_rect
        previous_clip = surface.get_clip()
        surface.set_clip(body)
        offset_y = body.y - self._scroll_y
        for text, size, bold, color, cx, cy in self._labels:
            rendered = self.ctx.fonts.render(
                text,
                size,
                color,
                bold=bold,
            )
            surface.blit(rendered, (body.x + cx, offset_y + cy))
        for button, _cx, _cy, _control_id in self._buttons:
            if button.rect.bottom >= body.y and button.rect.y <= body.bottom:
                button.draw(surface)
        surface.set_clip(previous_clip)

        max_scroll = self._max_scroll()
        if max_scroll > 0:
            track_h = body.height
            knob_h = max(
                self._sp(32),
                int(track_h * body.height / self._content_height),
            )
            knob_y = int(
                self._scroll_y
                / max_scroll
                * max(0, track_h - knob_h)
            )
            scrollbar_w = max(4, self._sp(4))
            x = self._panel_rect.right - self._sp(14)
            pygame.draw.rect(
                surface,
                (*theme.border_soft[:3], 70),
                (x, body.y, scrollbar_w, track_h),
                border_radius=max(2, scrollbar_w // 2),
            )
            pygame.draw.rect(
                surface,
                (*theme.accent[:3], 190),
                (x, body.y + knob_y, scrollbar_w, knob_h),
                border_radius=max(2, scrollbar_w // 2),
            )

        self._draw_status(surface)
        self._draw_footer(surface)

