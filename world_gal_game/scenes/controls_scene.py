"""Player-facing keyboard binding editor.

The page deliberately captures *physical* key presses while rebinding.  The
semantic action generated by the same key must not leak through and close the
overlay, activate another row, or advance the scene below it.
"""
from __future__ import annotations

from collections.abc import Iterable, Mapping
from typing import Callable

import pygame

from .base import Scene, SceneContext
from ..ui.input_bindings import (
    ACTION_SPECS,
    BindingProfile,
    InputAction,
    rebind_action,
)
from ..ui.system_chrome import ChromeRequest
from ..ui.widgets import Button, Panel


_GROUP_LABELS = {
    "dialogue": "對話",
    "navigation": "選單導覽",
    "menu": "選單導覽",
    "overlay": "功能與視窗",
    "system": "系統",
    "global": "全域",
}


class ControlsScene(Scene):
    """Scrollable, keyboard-first editor for the active binding profile."""

    def __init__(self, ctx: SceneContext):
        super().__init__(ctx)
        self.is_overlay = True
        self.on_close: Callable[[], None] | None = None
        self._scroll_y = 0
        self._focus = -1
        self._capture_action: str | None = None
        self._reset_pending = False
        self._status_kind = "info"
        self._status = ""
        self._layout_revision = 0
        self._touch_dragging = False
        self._touch_drag_moved = False
        self._touch_drag_distance = 0
        self._touch_drag_pending_y = 0

    # ---- model helpers -------------------------------------------------

    @property
    def capturing(self) -> bool:
        """Whether physical key capture currently owns the whole input frame."""
        return self._capture_action is not None

    @staticmethod
    def _specs() -> list:
        raw = ACTION_SPECS
        values: Iterable = raw.values() if isinstance(raw, Mapping) else raw
        return list(values)

    def _profile(self) -> BindingProfile:
        overrides = getattr(self.ctx.config, "input_bindings", {}) or {}
        return BindingProfile(dict(overrides))

    def _spec_for(self, action: str | None):
        if action is None:
            return None
        return next(
            (spec for spec in self._specs() if str(spec.id) == str(action)),
            None,
        )

    def _action_label(self, action: str | None) -> str:
        spec = self._spec_for(action)
        return str(spec.label) if spec is not None else str(action or "")

    @staticmethod
    def _group_label(group: object) -> str:
        key = str(group or "system")
        return _GROUP_LABELS.get(
            key,
            key.replace("_", " ").strip().title() or "其他",
        )

    def _sp(self, value: int) -> int:
        return max(1, int(round(value * self._density)))

    def _minimum_target_size(self) -> int:
        return max(44, self._sp(44))

    # ---- lifecycle / layout -------------------------------------------

    def enter(self, *, on_close=None, **_) -> None:
        self.on_close = on_close
        self._scroll_y = 0
        self._focus = -1
        self._capture_action = None
        self._reset_pending = False
        self._status_kind = "info"
        self._status = "選擇一項操作，然後按下要使用的新按鍵。"
        self._reset_touch_drag()
        self._build()

    def _make_button(
        self,
        width: int,
        height: int,
        label: str,
        on_click,
        *,
        style: str = "ghost",
        role: str = "action",
        selected: bool = False,
        tooltip: str | None = None,
    ) -> Button:
        line_h = self.ctx.fonts.get(
            self._button_font_size,
            bold=True,
        ).get_linesize()
        return Button(
            pygame.Rect(
                0,
                0,
                max(self._minimum_target, int(width)),
                max(self._minimum_target, int(height), line_h + self._sp(14)),
            ),
            label,
            fonts=self.ctx.fonts,
            theme=self.ctx.theme,
            font_size=self._button_font_size,
            on_click=on_click,
            style=style,
            tooltip=tooltip,
            chrome=self.ctx.ui_chrome,
            # Controls is a sub-page of Settings.  Reusing this screen id lets
            # pack chrome renderers apply their authored Settings treatment
            # without requiring a new plugin schema entry.
            screen="settings",
            role=role,
            selected=selected,
            text_align="left",
            motion=self.ctx.motion,
        )

    def _fit_button_text(self, text: str, width: int) -> str:
        font = self.ctx.fonts.get(self._button_font_size, bold=True)
        available = max(
            1,
            width - max(self._sp(24), self.ctx.theme.pad_m * 2),
        )
        normalized = " ".join(str(text).split())
        if font.size(normalized)[0] <= available:
            return normalized
        suffix = "…"
        while normalized and font.size(normalized + suffix)[0] > available:
            normalized = normalized[:-1]
        return normalized.rstrip() + suffix

    def _build(self, *, preserve_focus: str | None = None) -> None:
        theme = self.ctx.theme
        sw, sh = self.ctx.screen_size
        self._density = max(
            1.0,
            float(getattr(self.ctx.fonts, "scale", 1.0)),
        )
        self._minimum_target = self._minimum_target_size()
        self._title_font_size = self.ctx.config.font_size_header
        self._section_font_size = 18
        self._body_font_size = 16
        self._help_font_size = 13
        self._button_font_size = 15
        self._status_font_size = 14
        self._footer_font_size = 12

        self._title_line_h = self.ctx.fonts.get(
            self._title_font_size,
            bold=True,
        ).get_linesize()
        self._section_line_h = self.ctx.fonts.get(
            self._section_font_size,
            bold=True,
        ).get_linesize()
        self._body_line_h = self.ctx.fonts.get(
            self._body_font_size,
        ).get_linesize()
        self._status_line_h = self.ctx.fonts.get(
            self._status_font_size,
            bold=True,
        ).get_linesize()
        self._footer_line_h = self.ctx.fonts.get(
            self._footer_font_size,
            bold=True,
        ).get_linesize()
        button_line_h = self.ctx.fonts.get(
            self._button_font_size,
            bold=True,
        ).get_linesize()
        self._button_h = max(
            self._minimum_target,
            button_line_h + self._sp(14),
        )

        edge_x = max(16, self._sp(34))
        edge_y = max(16, self._sp(24))
        panel_w = min(self._sp(980), max(1, sw - edge_x * 2))
        panel_h = min(self._sp(760), max(1, sh - edge_y * 2))
        self._panel_rect = pygame.Rect(
            (sw - panel_w) // 2,
            (sh - panel_h) // 2,
            panel_w,
            panel_h,
        )
        self._panel = Panel(
            self._panel_rect,
            theme,
            fill=(*theme.bg_overlay[:3], 240),
            border=theme.border_strong,
            radius=theme.radius_l,
            border_width=2,
            chrome=self.ctx.ui_chrome,
            screen="settings",
            role="main",
            density=self._density,
        )

        inner_pad = max(16, self._sp(30))
        header_pad = max(10, self._sp(14))
        self._title_surface = self.ctx.fonts.render(
            "操作設定",
            self._title_font_size,
            theme.accent,
            bold=True,
        )
        close_text = (
            "取消設定"
            if self.capturing
            else self.ctx.localization.t("close", "關閉")
        )
        back_binding = (
            "Esc"
            if self.capturing
            else self._profile().primary_display(InputAction.BACK)
        )
        close_label = f"{close_text}　{back_binding}"
        close_line_h = self.ctx.fonts.get(
            self._button_font_size,
            bold=True,
        ).get_linesize()
        close_h = max(
            self._minimum_target,
            close_line_h + self._sp(14),
        )
        close_font = self.ctx.fonts.get(
            self._button_font_size,
            bold=True,
        )
        desired_close_w = max(
            self._minimum_target,
            self._sp(120),
            close_font.size(close_label)[0] + self._sp(24),
        )
        title_x = self._panel_rect.x + inner_pad
        title_right = title_x + self._title_surface.get_width()
        max_close_w = max(
            self._minimum_target,
            self._panel_rect.right
            - inner_pad
            - title_right
            - self._sp(12),
        )
        close_w = min(desired_close_w, max_close_w)
        if close_font.size(close_label)[0] + self._sp(24) > close_w:
            close_label = close_text
        self._header_h = (
            max(self._title_surface.get_height(), close_h)
            + header_pad * 2
        )
        title_y = (
            self._panel_rect.y
            + (self._header_h - self._title_surface.get_height()) // 2
        )
        self._title_rect = self._title_surface.get_rect(
            topleft=(title_x, title_y),
        )
        close_rect = pygame.Rect(
            self._panel_rect.right - inner_pad - close_w,
            self._panel_rect.y + (self._header_h - close_h) // 2,
            close_w,
            close_h,
        )
        self.close_btn = Button(
            close_rect,
            close_label,
            fonts=self.ctx.fonts,
            theme=theme,
            font_size=self._button_font_size,
            on_click=self._cancel_capture if self.capturing else self._close,
            style="ghost",
            chrome=self.ctx.ui_chrome,
            screen="settings",
            role="close",
            tooltip=f"{close_text}：{back_binding}",
            motion=self.ctx.motion,
        )
        self._header_divider_y = self._panel_rect.y + self._header_h - 1

        footer_pad = self._sp(8)
        footer_h = max(
            self._sp(34),
            self._footer_line_h + self._sp(12),
        )
        self._footer_rect = pygame.Rect(
            self._panel_rect.x + inner_pad,
            self._panel_rect.bottom - footer_pad - footer_h,
            max(1, self._panel_rect.width - inner_pad * 2),
            footer_h,
        )
        status_gap = self._sp(6)
        status_h = max(
            self._sp(46),
            self._status_line_h * 2 + self._sp(12),
        )
        self._status_rect = pygame.Rect(
            self._footer_rect.x,
            self._footer_rect.y - status_gap - status_h,
            self._footer_rect.width,
            status_h,
        )
        body_top = self._header_divider_y + self._sp(12)
        body_bottom = self._status_rect.top - self._sp(8)
        self._body_rect = pygame.Rect(
            self._panel_rect.x + inner_pad,
            body_top,
            max(1, self._panel_rect.width - inner_pad * 2),
            max(1, body_bottom - body_top),
        )

        content_edge = self._sp(4)
        content_width = max(
            1,
            min(
                self._sp(820),
                self._body_rect.width - content_edge * 2,
            ),
        )
        content_x = max(
            content_edge,
            (self._body_rect.width - content_width) // 2,
        )
        self._content_column_rect = pygame.Rect(
            content_x,
            0,
            content_width,
            1,
        )
        self._labels: list[tuple] = []
        # Button tuple: widget, content x/y, stable control id.
        self._buttons: list[tuple[Button, int, int, str]] = []
        self._content_regions: list[tuple[str, pygame.Rect]] = []

        row_gap = max(6, self._sp(8))
        section_before = max(8, self._sp(14))
        section_after = max(6, self._sp(10))
        cy = self._sp(2)

        def region(name: str, y: int, height: int) -> None:
            self._content_regions.append((
                name,
                pygame.Rect(
                    content_x,
                    y,
                    content_width,
                    max(1, height),
                ),
            ))

        def section(label: str, group_id: str) -> None:
            nonlocal cy
            cy += section_before
            self._labels.append((
                label,
                self._section_font_size,
                True,
                theme.accent_warm,
                content_x,
                cy,
            ))
            region(
                f"group:{group_id}",
                cy,
                self._section_line_h,
            )
            cy += self._section_line_h + section_after

        grouped: list[tuple[str, list]] = []
        for spec in self._specs():
            group = str(getattr(spec, "group", "system") or "system")
            found = next(
                (items for key, items in grouped if key == group),
                None,
            )
            if found is None:
                found = []
                grouped.append((group, found))
            found.append(spec)

        profile = self._profile()
        stacked = content_width < self._sp(620)
        label_w = (
            content_width
            if stacked
            else max(
                self._sp(210),
                min(self._sp(330), int(content_width * 0.42)),
            )
        )
        column_gap = max(8, self._sp(14))
        button_x = (
            content_x
            if stacked
            else content_x + label_w + column_gap
        )
        button_w = (
            content_width
            if stacked
            else content_width - label_w - column_gap
        )

        for group, specs in grouped:
            section(self._group_label(group), group)
            for spec in specs:
                action = str(spec.id)
                row_top = cy
                label = str(spec.label)
                if bool(getattr(spec, "required", False)):
                    label += "（必要）"
                label_y = cy
                if not stacked:
                    label_y += (
                        self._button_h - self._body_line_h
                    ) // 2
                self._labels.append((
                    label,
                    self._body_font_size,
                    False,
                    theme.text,
                    content_x,
                    label_y,
                ))
                if stacked:
                    cy += self._body_line_h + self._sp(6)
                binding_text = str(profile.display(action))
                button_label = (
                    "請按新按鍵（Esc 取消）"
                    if self._capture_action == action
                    else binding_text
                )
                button = self._make_button(
                    button_w,
                    self._button_h,
                    self._fit_button_text(button_label, button_w),
                    lambda action=action: self._start_capture(action),
                    style=(
                        "primary"
                        if self._capture_action == action
                        else "ghost"
                    ),
                    selected=self._capture_action == action,
                    tooltip=binding_text,
                )
                self._buttons.append((
                    button,
                    button_x,
                    cy,
                    f"action:{action}",
                ))
                cy += self._button_h
                region(
                    f"action:{action}",
                    row_top,
                    cy - row_top,
                )
                cy += row_gap

        section("重設", "reset")
        reset_label = (
            "確認恢復預設操作"
            if self._reset_pending
            else "恢復預設操作"
        )
        reset_button = self._make_button(
            min(content_width, self._sp(360)),
            self._button_h,
            reset_label,
            self._request_reset,
            style="danger" if self._reset_pending else "ghost",
            selected=self._reset_pending,
        )
        self._buttons.append((
            reset_button,
            content_x,
            cy,
            "reset",
        ))
        region("reset", cy, reset_button.rect.height)
        cy += reset_button.rect.height + self._sp(10)

        self._content_height = cy
        self._content_column_rect.height = max(1, cy)
        enabled = [
            index
            for index, (button, _cx, _cy, _control_id)
            in enumerate(self._buttons)
            if button.enabled
        ]
        wanted = preserve_focus
        if wanted is not None:
            self._focus = next(
                (
                    index
                    for index, (_button, _cx, _cy, control_id)
                    in enumerate(self._buttons)
                    if control_id == wanted
                ),
                -1,
            )
        if self._focus not in enabled:
            self._focus = enabled[0] if enabled else -1
        self._scroll_y = max(
            0,
            min(self._scroll_y, self._max_scroll()),
        )
        self._ensure_focus_visible()
        self._sync_focus_state()
        self._layout_revision += 1

    def _focused_control_id(self) -> str | None:
        if not 0 <= self._focus < len(self._buttons):
            return None
        return self._buttons[self._focus][3]

    def _rebuild(self) -> None:
        focus = self._focused_control_id()
        scroll = self._scroll_y
        self._build(preserve_focus=focus)
        self._scroll_y = max(0, min(scroll, self._max_scroll()))
        self._ensure_focus_visible()
        self._sync_focus_state()

    # ---- actions -------------------------------------------------------

    def _close(self) -> None:
        if self.on_close is not None:
            self.on_close()

    def _set_status(self, kind: str, text: str) -> None:
        self._status_kind = kind
        self._status = " ".join(str(text).split())

    def _cancel_capture(self) -> None:
        action = self._capture_action
        if action is None:
            return
        self._capture_action = None
        self._set_status(
            "info",
            f"已取消「{self._action_label(action)}」的按鍵設定。",
        )
        self._rebuild()

    def _start_capture(self, action: str) -> None:
        self._capture_action = action
        self._reset_pending = False
        self._set_status(
            "capture",
            f"正在設定「{self._action_label(action)}」："
            "請按一個新按鍵；Esc 取消。",
        )
        self._rebuild()

    @staticmethod
    def _physical_keys(inp) -> set[int]:
        physical = getattr(inp, "physical_keys_down", None)
        if physical is not None:
            return {int(key) for key in physical}
        return {
            int(event.key)
            for event in getattr(inp, "events", ())
            if event.type == pygame.KEYDOWN
            and not bool(getattr(event, "repeat", False))
        }

    def _capture_input(self, inp) -> None:
        """Consume one capture frame without routing anything to the page."""
        keys = self._physical_keys(inp)
        if not keys:
            return
        if pygame.K_ESCAPE in keys:
            self._cancel_capture()
            return
        if len(keys) != 1:
            self._set_status(
                "error",
                "一次只能按一個新按鍵，請放開後再試。",
            )
            return

        action = self._capture_action
        if action is None:
            return
        key = next(iter(keys))
        overrides = dict(
            getattr(self.ctx.config, "input_bindings", {}) or {},
        )
        result = rebind_action(
            overrides,
            action,
            key,
            resolution="swap",
        )
        if not bool(result.success):
            reason = {
                "reserved_key": "這是系統保留鍵，請改用其他按鍵。",
                "invalid_key": "無法辨識這個按鍵，請改用其他按鍵。",
                "unknown_action": "找不到要變更的操作。",
                "binding_conflict": "這個按鍵已用於同一操作情境。",
                "required_action_would_be_unbound": (
                    "這項變更會讓必要操作失去按鍵。"
                ),
            }.get(
                str(result.reason or ""),
                "這個按鍵無法安全套用。",
            )
            self._set_status("error", reason)
            return

        raw_swapped = getattr(result, "swapped_with", ()) or ()
        swapped_actions = (
            (str(raw_swapped),)
            if isinstance(raw_swapped, str)
            else tuple(str(item) for item in raw_swapped)
        )
        if len(swapped_actions) > 1:
            conflict_labels = "、".join(
                f"「{self._action_label(item)}」"
                for item in swapped_actions
            )
            self._set_status(
                "error",
                "這個按鍵同時與多項操作衝突"
                f"（{conflict_labels}），請改用其他按鍵。",
            )
            return

        self.ctx.config.input_bindings = dict(result.overrides)
        try:
            self.ctx.config.save_to_disk()
        except OSError as exc:
            self._set_status(
                "error",
                f"按鍵已套用，但無法寫入設定檔：{exc}",
            )
        else:
            key_label = BindingProfile(
                dict(result.overrides),
            ).primary_display(action)
            swapped_labels = "、".join(
                f"「{self._action_label(item)}」"
                for item in swapped_actions
            )
            detail = (
                f"；並與{swapped_labels}交換"
                if swapped_labels
                else ""
            )
            self._set_status(
                "success",
                f"已將「{self._action_label(action)}」設為 "
                f"{key_label}{detail}。",
            )
        self._capture_action = None
        self._reset_pending = False
        self._rebuild()

    def _request_reset(self) -> None:
        self._capture_action = None
        if not self._reset_pending:
            self._reset_pending = True
            self._set_status(
                "warning",
                "再次選擇「確認恢復預設操作」才會清除自訂按鍵。",
            )
            self._rebuild()
            return
        self.ctx.config.input_bindings = {}
        try:
            self.ctx.config.save_to_disk()
        except OSError as exc:
            self._set_status(
                "error",
                f"已恢復本次執行的預設操作，但無法寫入設定檔：{exc}",
            )
        else:
            self._set_status(
                "success",
                "已恢復預設操作；必要的確認與返回操作保持可用。",
            )
        self._reset_pending = False
        self._rebuild()

    # ---- focus / scrolling --------------------------------------------

    def _max_scroll(self) -> int:
        return max(0, self._content_height - self._body_rect.height)

    def _reposition(self) -> None:
        body = self._body_rect
        for button, cx, cy, _control_id in self._buttons:
            button.rect.topleft = (
                body.x + cx,
                body.y + cy - self._scroll_y,
            )

    def _sync_focus_state(self) -> None:
        for index, (button, _cx, _cy, _control_id) in enumerate(
            self._buttons,
        ):
            button.focused = index == self._focus and button.enabled

    def _control_region(self, control_id: str) -> pygame.Rect | None:
        return next(
            (
                region
                for name, region in self._content_regions
                if name == control_id
            ),
            None,
        )

    def _ensure_focus_visible(self) -> None:
        if not 0 <= self._focus < len(self._buttons):
            self._scroll_y = max(
                0,
                min(self._scroll_y, self._max_scroll()),
            )
            self._reposition()
            return
        button, content_x, content_y, control_id = self._buttons[self._focus]
        focus_region = self._control_region(control_id)
        if focus_region is None:
            focus_region = pygame.Rect(
                content_x,
                content_y,
                button.rect.width,
                button.rect.height,
            )
        padding = self._sp(4)
        focus_top = max(0, focus_region.top - padding)
        focus_bottom = focus_region.bottom + padding
        if focus_top < self._scroll_y:
            self._scroll_y = focus_top
        elif focus_bottom > self._scroll_y + self._body_rect.height:
            self._scroll_y = focus_bottom - self._body_rect.height
        self._scroll_y = max(
            0,
            min(self._scroll_y, self._max_scroll()),
        )
        self._reposition()

    def _reset_touch_drag(self) -> None:
        self._touch_dragging = False
        self._touch_drag_moved = False
        self._touch_drag_distance = 0
        self._touch_drag_pending_y = 0

    def _update_touch_scroll(self, inp) -> bool:
        """Update body scrolling and report whether pointer input is consumed."""
        started = bool(getattr(inp, "touch_started", False))
        active = bool(getattr(inp, "touch_active", False))
        released = bool(getattr(inp, "touch_released", False))

        if started:
            self._reset_touch_drag()
            if self._body_rect.collidepoint(
                getattr(inp, "mouse_pos", (-1, -1)),
            ):
                self._touch_dragging = True

        if not self._touch_dragging:
            return False

        delta_y = int(getattr(inp, "touch_delta", (0, 0))[1])
        if delta_y:
            self._touch_drag_distance += abs(delta_y)
            self._touch_drag_pending_y += delta_y
            threshold = max(6, self._sp(8))
            if self._touch_drag_distance >= threshold:
                self._touch_drag_moved = True
            if self._touch_drag_moved:
                self._scroll_y -= self._touch_drag_pending_y
                self._touch_drag_pending_y = 0
                self._scroll_y = max(
                    0,
                    min(self._scroll_y, self._max_scroll()),
                )
                self._reposition()

        ending = released or (not active and not started)
        consume = self._touch_drag_moved or not ending
        if ending:
            self._reset_touch_drag()
        return consume

    @staticmethod
    def _action_pressed(inp, action: str) -> bool:
        pressed = getattr(inp, "pressed", None)
        return bool(callable(pressed) and pressed(action))

    @classmethod
    def _navigation_delta(cls, inp) -> int:
        if cls._action_pressed(inp, InputAction.NAV_UP):
            return -1
        if cls._action_pressed(inp, InputAction.NAV_DOWN):
            return 1
        nav = int(getattr(inp, "nav", 0))
        if nav:
            return -1 if nav < 0 else 1
        return 0

    def _move_focus(self, delta: int) -> None:
        enabled = [
            index
            for index, (button, _cx, _cy, _control_id)
            in enumerate(self._buttons)
            if button.enabled
        ]
        if not enabled or not delta:
            return
        if self._focus not in enabled:
            self._focus = enabled[0] if delta > 0 else enabled[-1]
        else:
            position = enabled.index(self._focus)
            self._focus = enabled[(position + delta) % len(enabled)]
        self._ensure_focus_visible()
        self._sync_focus_state()

    # ---- frame ---------------------------------------------------------

    def update(self, dt: float, inp) -> None:
        # Capture is a modal input state.  Returning on every frame, including
        # frames without a key, prevents mouse/controller actions and mapped
        # semantic actions from reaching this page or the scene below.
        if self._capture_action is not None:
            close_clicked = (
                bool(getattr(inp, "mouse_clicked", False))
                and self.close_btn.rect.collidepoint(
                    getattr(inp, "mouse_pos", (-1, -1)),
                )
            )
            back_pressed = (
                self._action_pressed(inp, InputAction.BACK)
                or bool(getattr(inp, "cancel", False))
            )
            if close_clicked or back_pressed:
                self._cancel_capture()
            else:
                self._capture_input(inp)
            return

        back_pressed = (
            self._action_pressed(inp, InputAction.BACK)
            or bool(getattr(inp, "cancel", False))
        )
        if back_pressed:
            if self._reset_pending:
                self._reset_pending = False
                self._set_status("info", "已取消恢復預設操作。")
                self._rebuild()
            else:
                self._close()
            return

        if self._body_rect.collidepoint(inp.mouse_pos):
            self._scroll_y -= int(inp.mouse_wheel) * self._sp(44)

        if self._update_touch_scroll(inp):
            return

        nav_delta = self._navigation_delta(inp)
        if nav_delta:
            self._move_focus(nav_delta)
        confirm_pressed = (
            self._action_pressed(inp, InputAction.CONFIRM_ADVANCE)
            or bool(getattr(inp, "confirm", False))
        )
        if confirm_pressed and (
            0 <= self._focus < len(self._buttons)
        ):
            revision = self._layout_revision
            button = self._buttons[self._focus][0]
            if button.activate() or self._layout_revision != revision:
                return

        self._scroll_y = max(
            0,
            min(self._scroll_y, self._max_scroll()),
        )
        self._reposition()

        close_clicked = (
            inp.mouse_clicked
            and self.close_btn.rect.collidepoint(inp.mouse_pos)
        )
        self.close_btn.update(dt, inp)
        if close_clicked:
            return

        body = self._body_rect
        pointer_focus = next(
            (
                index
                for index, (button, _cx, _cy, _control_id)
                in enumerate(self._buttons)
                if (
                    button.enabled
                    and body.contains(button.rect)
                    and button.rect.collidepoint(inp.mouse_pos)
                    and inp.mouse_clicked
                )
            ),
            None,
        )
        if pointer_focus is not None:
            self._focus = pointer_focus
        self._sync_focus_state()

        revision = self._layout_revision
        for button, _cx, _cy, _control_id in list(self._buttons):
            if body.contains(button.rect):
                button.update(dt, inp)
            else:
                button._hover = False
                button._hover_t = 0.0
            if self._layout_revision != revision:
                return

