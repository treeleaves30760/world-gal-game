_TO_TRADITIONAL = str.maketrans("".join(sorted(SIMPLIFIED_ONLY)), _TRADITIONAL_FORMS)
#: Words the one-for-one table gets wrong (发 is both 發 and 髮).
_WORD_FIXES = (
    ("頭發", "頭髮"), ("發型", "髮型"), ("理發", "理髮"), ("長發", "長髮"),
    ("短發", "短髮"), ("黑發", "黑髮"), ("白發", "白髮"), ("金發", "金髮"),
    ("發絲", "髮絲"), ("發梢", "髮梢"), ("發夾", "髮夾"), ("發圈", "髮圈"),
    ("日歷", "日曆"), ("月歷", "月曆"), ("鬧鍾", "鬧鐘"),
    ("時鍾", "時鐘"), ("鍾聲", "鐘聲"),
)


#: Simplified characters that stand for more than one Traditional character,
#: where the table's single answer is a guess.
AMBIGUOUS_SIMPLIFIED = frozenset("发钟历获脏团汇饥苏坛纤尽签须")


def to_traditional(text: str) -> str:
    """Replace Simplified-only characters with their Traditional forms."""
    out = text.translate(_TO_TRADITIONAL)
    if out != text:
        for wrong, right in _WORD_FIXES:
            out = out.replace(wrong, right)
    return out


def repair_slip(text: str, limit: int = 3) -> str | None:
    """Fix a small, unambiguous Simplified slip in a Traditional line.

    Returns the corrected line, or ``None`` when there is nothing to fix or
    the slip is not safe to fix by table: an ambiguous character, or more
    than ``limit`` distinct ones (the line has drifted into the other script
    and should be written again).
    """
    stray = {ch for ch in text if ch in SIMPLIFIED_ONLY}
    if not stray or len(stray) > limit or stray & AMBIGUOUS_SIMPLIFIED:
        return None
    return to_traditional(text)
